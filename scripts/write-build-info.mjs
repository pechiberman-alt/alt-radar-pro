// Stamps every build with an id both the client bundle and the server share,
// so an app instance can tell it is running old code. Runs as npm "prebuild".
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let id = (process.env.GITHUB_SHA || "").slice(0, 7);
if (!id) {
  try {
    id = execSync("git rev-parse --short HEAD").toString().trim();
  } catch {
    id = "dev";
  }
}
writeFileSync(
  new URL("../lib/build-info.ts", import.meta.url),
  `// Generated by scripts/write-build-info.mjs at build time.\nexport const BUILD_ID: string = ${JSON.stringify(id)};\nexport const BUILT_AT: string = ${JSON.stringify(new Date().toISOString())};\n`,
);
console.log(`build-info: ${id}`);
